import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const pkg=JSON.parse(read('package.json'));
const worker=read('src/lib/ocrWorkerManager.ts');
const reader=read('src/modules/card-reader/manualCalibrationFastReader.ts');
const vendor=read('scripts/vendor-tesseract-assets.mjs');
const progress=read('src/components/ProgressBarsV4010.tsx');
assert.equal(pkg.version,'40.80.0');
assert.match(worker,/gzip:\s*false/);
assert.match(vendor,/4\.0\.0_best_int/);
assert.match(vendor,/por\.traineddata'/);
assert.doesNotMatch(vendor,/public\/tesseract\/lang\/por\.traineddata\.gz'/);
assert.match(reader,/TOTAL_READER_DEADLINE_MS = 90_000/);
const macroPlansBlock=reader.match(/const MACRO_PLANS:\s*MacroPlan\[\]\s*=\s*\[([\s\S]*?)\n\];/)?.[1];
assert.ok(macroPlansBlock,'MACRO_PLANS não foi encontrado no leitor manual.');
const macroIds=[...macroPlansBlock.matchAll(/\{\s*id:\s*'([^']+)'/g)].map((match)=>match[1]);
assert.deepEqual(macroIds,['identity','card','bio','positions','boosters','progression','attributes','physical','skills']);
assert.match(progress,/deadlineMs\?: number/);
assert.match(progress,/safeRemaining/);
console.log('v40.30 aprovada: OCR BEST descompactado, 9 macros primários reais, teto de 90 s e ETA não explosiva.');
